SHELLS=(200,500,700,1100)

def magnitude_mean_correction(mean, magnitude_sd):
    """Invert single-coil Rice moments with an explicit boundary policy.

    MP-PCA can produce negative background values: project these to zero.
    Zero estimated noise leaves nonnegative means unchanged. Ratios above
    the validated lookup use the high-SNR expansion (relative error <1e-12
    at this transition), avoiding arbitrary clipping of high-SNR signals.
    """
    values, noise = np.broadcast_arrays(np.asarray(mean, dtype=np.float64),
                                       np.asarray(magnitude_sd, dtype=np.float64))
    if np.any(~np.isfinite(values)) or np.any(~np.isfinite(noise)):
        raise ValueError("Magnitude means and noise must be finite")
    if np.any(noise < 0):
        raise ValueError("Magnitude SD cannot be negative")
    positive = np.maximum(values, 0)
    result = positive.copy()
    valid = (noise > 0) & (positive > 0)
    ratio = np.divide(positive, noise, out=np.zeros_like(positive), where=noise > 0)
    high = valid & (ratio > 1000.)
    ordinary = valid & ~high
    if np.any(ordinary):
        result[ordinary] = invert_rice_magnitude_moments(
            positive[ordinary], noise[ordinary])[0]
    if np.any(high):
        x, s = positive[high], noise[high]
        result[high] = x - s*s/(2*x) - 3*s**4/(8*x**3)
    rayleigh_ratio = np.sqrt(np.pi/2)/np.sqrt(2-np.pi/2)
    return result, {
        "n_values": int(values.size), "n_nonfinite": 0,
        "n_negative_mean": int(np.sum(values < 0)),
        "n_zero_noise": int(np.sum(noise == 0)),
        "n_projected_below_rayleigh": int(np.sum(valid & (ratio < rayleigh_ratio))),
        "n_high_snr_expansion": int(np.sum(high)),
    }


def shell_mean_noise_sd(spatial_sd, applied_volume_scales):
    """SD of an independent-volume mean after unequal intensity scaling."""
    noise = np.asarray(spatial_sd, dtype=np.float64)
    scales = np.asarray(applied_volume_scales, dtype=np.float64)
    if scales.ndim != 1 or not len(scales):
        raise ValueError("Volume scales must be a nonempty vector")
    if (np.any(~np.isfinite(noise)) or np.any(noise < 0)
            or np.any(~np.isfinite(scales)) or np.any(scales <= 0)):
        raise ValueError("Noise must be finite/nonnegative and scales finite/positive")
    return noise * np.sqrt(np.sum(scales**2)) / len(scales)


def assemble_scaled_covariance_state(*, s0, shell_signals, baseline_mean_sd, shell_mean_sd):
    """Build the shared-baseline model from SDs already in shell-mean units."""
    baseline = np.asarray(s0, dtype=np.float64).reshape(-1)
    baseline_sd = np.asarray(baseline_mean_sd, dtype=np.float64).reshape(-1)
    if baseline_sd.shape != baseline.shape:
        raise ValueError("Baseline mean SD and signal must have matching shapes")
    if set(shell_signals) != set(SHELLS) or set(shell_mean_sd) != set(SHELLS):
        raise ValueError("Exactly the four thermometry shells are required")
    if np.any(~np.isfinite(baseline_sd)) or np.any(baseline_sd < 0):
        raise ValueError("Baseline mean SD must be finite and nonnegative")
    shape = (len(baseline), 4)
    temperatures, tau, eta = [np.full(shape, np.nan) for _ in range(3)]
    for i, b in enumerate(SHELLS):
        signal = np.asarray(shell_signals[b], dtype=np.float64).reshape(-1)
        sd = np.asarray(shell_mean_sd[b], dtype=np.float64).reshape(-1)
        if signal.shape != baseline.shape or sd.shape != baseline.shape:
            raise ValueError("Shell signals/noise must match the baseline shape")
        if np.any(~np.isfinite(sd)) or np.any(sd < 0):
            raise ValueError("Shell mean SD must be finite and nonnegative")
        with np.errstate(divide="ignore", invalid="ignore", over="ignore"):
            adc = np.log(baseline/signal)/b
            log_term = np.log(19.649/adc)
            t = 2732/log_term - 273.15
            derivative = np.abs(2732/(adc*log_term**2))
            shared = derivative*baseline_sd/(b*baseline)
            independent = derivative*sd/(b*signal)
            uncertainty = np.hypot(shared, independent)
        good = ((baseline > 0) & (signal > 0) & np.isfinite(adc) & (adc > 1e-6)
                & np.isfinite(t) & np.isfinite(shared) & np.isfinite(independent)
                & (uncertainty > 0) & (uncertainty < 20))
        temperatures[:, i] = np.where(good, t, np.nan)
        tau[:, i] = np.where(good, shared, np.nan)
        eta[:, i] = np.where(good, independent, np.nan)
    valid = (np.all(np.isfinite(temperatures), axis=1)
             & np.all(np.isfinite(tau) & (tau >= 0), axis=1)
             & np.all(np.isfinite(eta) & (eta > 0), axis=1))
    median, mad, rms = [np.full(len(baseline), np.nan) for _ in range(3)]
    tau_normalised, eta_normalised, weights = [np.full(shape, np.nan) for _ in range(3)]
    if np.any(valid):
        median[valid] = np.median(temperatures[valid], axis=1)
        mad[valid] = mad4(temperatures[valid])
        rms[valid], tau_normalised[valid], eta_normalised[valid] = (
            normalise_temperature_error_components(tau[valid], eta[valid]))
        weights[valid] = np.hypot(tau[valid], eta[valid])/rms[valid, None]
    return dict(temperature_stack=temperatures, tau_stack=tau, eta_stack=eta,
                sigma_temperature_stack=np.hypot(tau, eta), temperature=median,
                mad=mad, sigma_rms=rms, weights=weights, tau_normalised=tau_normalised,
                eta_normalised=eta_normalised, z=mad/rms, valid=valid)


def compute_covariance_conditioned(
    state: Dict[str, Any],
    normals: Dict[str, np.ndarray],
    refinement_margin: float,
    ultra_margin: float,
) -> Tuple[np.ndarray, np.ndarray, Dict[str, Any]]:
    """Estimate covariance-aware null medians with adaptive QMC refinement."""
    eligible = (
        state["valid"]
        & (state["region"] != "")
        & (state["temperature"] >= 25.0)
    )
    eligible_indices = np.flatnonzero(eligible)
    z = state["z"][eligible]
    tau = state["tau_normalised"][eligible]
    eta = state["eta_normalised"][eligible]
    temperature = state["temperature"][eligible]

    thresholds = covariance_null_medians(
        tau, eta, normals["coarse"], batch_size=512
    )
    coarse_classification = classify_at_null_median(z, thresholds, temperature)

    refined = np.abs(z - thresholds) <= refinement_margin
    coarse_refined_delta = np.array([], dtype=np.float64)
    coarse_refined_flips = 0
    if np.any(refined):
        old_thresholds = thresholds[refined].copy()
        old_classification = coarse_classification[refined]
        thresholds[refined] = covariance_null_medians(
            tau[refined], eta[refined], normals["refined"], batch_size=64
        )
        coarse_refined_delta = thresholds[refined] - old_thresholds
        coarse_refined_flips = int(
            np.sum(
                old_classification
                != classify_at_null_median(
                    z[refined], thresholds[refined], temperature[refined]
                )
            )
        )

    ultra = refined & (np.abs(z - thresholds) <= ultra_margin)
    ultra_disagreement = np.zeros(len(z), dtype=bool)
    ultra_threshold_difference = np.array([], dtype=np.float64)
    if np.any(ultra):
        threshold_a = covariance_null_medians(
            tau[ultra], eta[ultra], normals["ultra_a"], batch_size=16
        )
        threshold_b = covariance_null_medians(
            tau[ultra], eta[ultra], normals["ultra_b"], batch_size=16
        )
        class_a = classify_at_null_median(z[ultra], threshold_a, temperature[ultra])
        class_b = classify_at_null_median(z[ultra], threshold_b, temperature[ultra])
        ultra_threshold_difference = threshold_a - threshold_b
        local_disagreement = class_a != class_b
        ultra_disagreement[np.flatnonzero(ultra)] = local_disagreement
        thresholds[ultra] = 0.5 * (threshold_a + threshold_b)

    resolved = ultra_disagreement.copy()
    resolve_disagreement = np.zeros(len(z), dtype=bool)
    resolve_threshold_difference = np.array([], dtype=np.float64)
    if np.any(resolved):
        threshold_a = covariance_null_medians(
            tau[resolved], eta[resolved], normals["resolve_a"], batch_size=4
        )
        threshold_b = covariance_null_medians(
            tau[resolved], eta[resolved], normals["resolve_b"], batch_size=4
        )
        class_a = classify_at_null_median(
            z[resolved], threshold_a, temperature[resolved]
        )
        class_b = classify_at_null_median(
            z[resolved], threshold_b, temperature[resolved]
        )
        resolve_threshold_difference = threshold_a - threshold_b
        local_disagreement = class_a != class_b
        resolve_disagreement[np.flatnonzero(resolved)] = local_disagreement
        thresholds[resolved] = 0.5 * (threshold_a + threshold_b)

    final_power = resolve_disagreement.copy()
    if np.any(final_power):
        thresholds[final_power] = covariance_null_medians(
            tau[final_power], eta[final_power], normals["final"], batch_size=1
        )

    retained_eligible = classify_at_null_median(z, thresholds, temperature)
    retained = np.zeros(len(state["valid"]), dtype=bool)
    null_median = np.full(len(state["valid"]), np.nan)
    retained[eligible_indices] = retained_eligible
    null_median[eligible_indices] = thresholds

    diagnostics = {
        "n_eligible": int(len(eligible_indices)),
        "n_refined": int(refined.sum()),
        "n_ultra": int(ultra.sum()),
        "n_ultra_scramble_disagreement": int(ultra_disagreement.sum()),
        "n_checked_at_resolve": int(resolved.sum()),
        "n_resolve_scramble_disagreement": int(resolve_disagreement.sum()),
        "n_adjudicated_at_final_power": int(final_power.sum()),
        "coarse_to_refined_classification_flips": coarse_refined_flips,
        "coarse_refined_threshold_delta_median_abs": (
            float(np.median(np.abs(coarse_refined_delta)))
            if len(coarse_refined_delta)
            else 0.0
        ),
        "coarse_refined_threshold_delta_max_abs": (
            float(np.max(np.abs(coarse_refined_delta)))
            if len(coarse_refined_delta)
            else 0.0
        ),
        "ultra_scramble_threshold_delta_median_abs": (
            float(np.median(np.abs(ultra_threshold_difference)))
            if len(ultra_threshold_difference)
            else 0.0
        ),
        "ultra_scramble_threshold_delta_max_abs": (
            float(np.max(np.abs(ultra_threshold_difference)))
            if len(ultra_threshold_difference)
            else 0.0
        ),
        "resolve_scramble_threshold_delta_median_abs": (
            float(np.median(np.abs(resolve_threshold_difference)))
            if len(resolve_threshold_difference)
            else 0.0
        ),
        "resolve_scramble_threshold_delta_max_abs": (
            float(np.max(np.abs(resolve_threshold_difference)))
            if len(resolve_threshold_difference)
            else 0.0
        ),
    }
    return retained, null_median, diagnostics


def make_qmc_normals(args: argparse.Namespace, dimension: int) -> Dict[str, np.ndarray]:
    """Create deterministic stage-specific Gaussian Sobol draws."""
    return {
        "coarse": sobol_gaussian_draws(args.coarse_power, 1729, dimension),
        "refined": sobol_gaussian_draws(args.refined_power, 2718, dimension),
        "ultra_a": sobol_gaussian_draws(args.ultra_power, 31415, dimension),
        "ultra_b": sobol_gaussian_draws(args.ultra_power, 92653, dimension),
        "resolve_a": sobol_gaussian_draws(args.resolve_power, 161803, dimension),
        "resolve_b": sobol_gaussian_draws(args.resolve_power, 141421, dimension),
        "final": sobol_gaussian_draws(args.final_power, 173205, dimension),
    }
